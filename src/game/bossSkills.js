// مهارات الحيوانات في قتال البوس.
// سلبية (Passive): تعمل دائمًا بحسب عنصر الحيوان، وتقوى مع ندرته.
// فعّالة (Active): مهارة واحدة بحسب العنصر، تُستخدم تلقائيًا كل عدة جولات (كولداون).
const D = require("./data");

// مضاعف الندرة: شائع ... سماوي
const RM = [1, 1.25, 1.6, 2, 2.5, 3.1, 4];
// كولداون المهارة الفعّالة بالجولات: كلما ارتفعت الندرة قلّ الانتظار
const CD = [5, 5, 4, 4, 3, 3, 2];

const rarityOf = pet => D.SPECIES[pet.sp].r;
const rm = pet => RM[rarityOf(pet)] || 1;
const cdOf = pet => CD[rarityOf(pet)] || 5;
const pct = x => Math.round(x * 100) + "%";

// قيم المهارات (كلها تُضرب في مضاعف الندرة ثم تُقصّ بحدود معقولة)
const PASSIVE = {
    fire:    { n: "حرق",      e: "🔥", t: m => `ضرر إضافي +${pct(0.10 * m)} على كل هجمة` },
    water:   { n: "تدفّق",    e: "💧", t: m => `يعالج أضعف حليف ${pct(0.03 * m)} من حياته كل جولة` },
    plant:   { n: "جذور",     e: "🌿", t: m => `يستعيد ${pct(0.03 * m)} من حياته كل جولة` },
    earth:   { n: "صلابة",    e: "🪨", t: m => `يقلّل الضرر الذي يصيبه ${pct(Math.min(0.6, 0.08 * m))}` },
    thunder: { n: "صاعقة",    e: "⚡", t: m => `فرصة ${pct(Math.min(0.6, 0.12 * m))} لضربة مزدوجة` },
    light:   { n: "بركة",     e: "✨", t: m => `يرفع ضرر الفريق +${pct(0.04 * m)}` },
    dark:    { n: "امتصاص",   e: "🌑", t: m => `يشفي نفسه ${pct(Math.min(0.6, 0.12 * m))} من ضرره` }
};
const ACTIVE = {
    fire:    { n: "انفجار",       e: "💥", t: m => `ضربة بقوة ×${(2.2 + 0.15 * m).toFixed(1)}` },
    water:   { n: "موجة الشفاء",  e: "🌊", t: m => `يعالج كل الفريق ${pct(0.10 * m)} من حياتهم` },
    plant:   { n: "سياج الشوك",   e: "🛡️", t: m => `درع للفريق يمتص ${pct(0.06 * m)} من حياة كل حيوان` },
    earth:   { n: "استفزاز",      e: "😤", t: m => `يجذب هجمات الزعيم جولتين ويقلل ضررها ${pct(Math.min(0.7, 0.35 + 0.05 * m))}` },
    thunder: { n: "صعق",          e: "🌩️", t: m => `ضربة ×${(1.6 + 0.1 * m).toFixed(1)} وتشلّ الزعيم جولة` },
    light:   { n: "ترميم",        e: "💫", t: m => `يحيي حليفًا ساقطًا بـ ${pct(Math.min(0.9, 0.25 + 0.06 * m))} من حياته، وإلا يعالج الأضعف ${pct(0.28 * m)}` },
    dark:    { n: "لعنة",         e: "☠️", t: m => `الزعيم يتلقى +${pct(Math.min(0.8, 0.2 + 0.03 * m))} ضرر لـ 3 جولات` }
};

// وصف مهارات حيوان للعرض
function describe(pet) {
    const m = rm(pet), p = PASSIVE[pet.el], a = ACTIVE[pet.el];
    return {
        passive: `${p.e} ${p.n}: ${p.t(m)}`,
        active: `${a.e} ${a.n} (كل ${cdOf(pet)} جولات): ${a.t(m)}`
    };
}

module.exports = { RM, CD, PASSIVE, ACTIVE, rm, cdOf, rarityOf, describe };