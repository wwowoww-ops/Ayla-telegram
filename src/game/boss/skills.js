// وصف مهارات حيوان للعرض
function describe(pet) {
    const m = rm(pet), p = PASSIVE[pet.el], sk = SKILLS[pet.el];
    return {
        passive: `${p.e} ${p.n}: ${p.t(m)}`,
        skills: sk.map((s, i) => `${s.e} ${s.n} (كل ${cdOf(pet, i)}): ${s.t(m)}`)
    };
}

