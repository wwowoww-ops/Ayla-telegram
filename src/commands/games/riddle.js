// الحزورات
const { pick, cmd } = require("../../lib/util");
const { riddle, alive } = require("../../lib/rounds");

const RIDDLES = [
    ["ما هو الشيء الذي له أسنان ولا يعض؟", ["المشط", "مشط"]],
    ["ما هو الشيء الذي يمشي بلا أرجل ويبكي بلا عيون؟", ["السحاب", "الغيمة", "الغيم", "سحاب"]],
    ["شيء كلما أخذت منه كبر، ما هو؟", ["الحفرة", "حفرة"]],
    ["ما هو الشيء الذي يكتب ولا يقرأ؟", ["القلم", "قلم"]],
    ["ما هو الشيء الذي كلما زاد نقص؟", ["العمر", "عمر"]],
    ["ما هو الشيء الذي يسمع بلا أذن ويتكلم بلا لسان؟", ["الهاتف", "هاتف", "التلفون", "الجوال"]],
    ["ما هو الشيء الذي تملكه ولكن الآخرين يستخدمونه أكثر منك؟", ["اسمك", "الاسم", "اسم"]],
    ["ما هو الشيء الذي يوجد في وسط باريس؟", ["حرف الراء", "الراء", "راء", "ر"]],
    ["ما هو الشيء الذي يرتفع وينخفض ولا يتحرك؟", ["الدرج", "السلم", "الدرجات", "درج"]],
    ["ما هو الشيء الذي يحمل مفاتيح ولا يفتح الأبواب؟", ["البيانو", "لوحة المفاتيح", "الكيبورد", "بيانو"]]
];

module.exports = function (bot) {
    cmd(bot, ["حزورة", "حزوره", "لغز"], async ctx => {
        const cur = alive(riddle, ctx.chat.id);
        if (cur) return ctx.reply("🧩 الحزورة الحالية:\n" + cur.q + "\n\n(للكشف عن الجواب اكتب: حل)");
        const [q, answers] = pick(RIDDLES);
        riddle.set(ctx.chat.id, { q, answers, at: Date.now() });
        return ctx.reply("🧩 حزورة:\n" + q + "\n\nأول من يجيب صحيحًا يفوز! (للتخطي: حل)");
    });
};